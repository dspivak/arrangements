"""The JavaScript written by ``scripts/export_step_js.py`` steps as the library composite does.

The feeding model, ``feeding_composed.feeding_with_slot`` (``feeding.feeding``), is exported for
one, two and three casings with the places and the page's knobs as inputs: its step (four
Runge-Kutta rounds of ``PhiK``), its readouts, its start and its search curve, each run under node
at 40 calls and checked against the library to 1e-12. ``hh_atp``'s step, regenerated by the same
exporter, must agree with the committed ``viewer/hh-atp-dynamics.js``. (Until 2026-11-23 the
hinged feeding model's step was checked too, on the hand-typed page's states; it left the library
then.) No equation is typed in the exporter or here.
"""
import importlib.util
import json
import subprocess
from pathlib import Path

import jax
import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
VIEWER = ROOT / "viewer"
DRIVER = VIEWER / "exported-step-driver.js"
_spec = importlib.util.spec_from_file_location("export_step_js", ROOT / "scripts" / "export_step_js.py")
exporter = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(exporter)


def run_node(path, states, tmp_path, *flags):
    data = tmp_path / f"{path.stem}-states.json"
    data.write_text(json.dumps([np.asarray(s).tolist() for s in states]))
    out = subprocess.check_output(["node", str(DRIVER), str(path), str(data), *flags], text=True)
    return np.asarray(json.loads(out)["results"])


def test_hh_atp_matches_committed_export(tmp_path):
    from arrangements import hh_atp
    state, step, _, _ = hh_atp.live_membrane()
    path = tmp_path / "hh.js"
    path.write_text(exporter.module([("step", exporter.javascript(step, state, "step"))], "Membrane", {}, "test"))
    rng = np.random.default_rng(0)
    states = [np.asarray(state) * (1 + .05 * rng.standard_normal(state.shape)) for _ in range(20)]
    got = run_node(path, states, tmp_path)
    committed = run_node(VIEWER / "hh-atp-dynamics.js", states, tmp_path, "--global", "MembraneDynamics")
    np.testing.assert_allclose(got, committed, rtol=0, atol=1e-12)
    np.testing.assert_allclose(got, np.asarray([np.asarray(jax.jit(step)(s)) for s in states]), rtol=0, atol=1e-12)


@pytest.mark.parametrize("count", [1, 2, 3])
def test_slot_step_and_observe(count, tmp_path):
    """``feeding_with_slot``'s four Runge-Kutta rounds and its readouts, with the places and the
    page's knobs as inputs: 20 states every 300 steps along a library run at the page's places and
    knobs, and 20 perturbed starting states at random places, knobs and integer seeds."""
    functions, examples, metadata = exporter.slot_model(count)
    step, observe, example = functions["step"], functions["observe"], examples["step"]
    path = tmp_path / f"slot-{count}.js"
    path.write_text(exporter.module([("step", exporter.javascript(step, example, "step")),
                                     ("observe", exporter.javascript(observe, example, "observe",
                                                                     fields=exporter.OBSERVED)),
                                     ("start", exporter.javascript(functions["start"], examples["start"], "start")),
                                     ("curve", exporter.javascript(functions["curve"], examples["curve"], "curve",
                                                                   fields=("usual", "density")))],
                                    "FeedingSlot", metadata, "test"))
    initial, places, params = example
    assert sum(s["size"] for s in metadata["stores"]) == len(initial) == len(metadata["entryStore"])
    assert sorted({s["casing"] for s in metadata["stores"] if "casing" in s}) == list(range(count))
    run = jax.jit(lambda s, p, q: jax.lax.fori_loop(0, 300, lambda _, x: step(x, p, q), s))
    calls, s = [], initial
    for _ in range(20):
        calls.append((s, places, params))
        s = run(s, places, params)
    rng = np.random.default_rng(count)
    for _ in range(20):
        knobs = params * (1 + .1 * rng.standard_normal(params.shape))
        knobs[metadata["knobs"].index("searchSeed")] = rng.integers(0, 1000)
        calls.append((initial + .01 * rng.standard_normal(initial.shape), np.sort(rng.uniform(-8, 8, count)), knobs))
    data = tmp_path / "calls.json"
    data.write_text(json.dumps([[np.asarray(a).tolist() for a in c] for c in calls]))
    node = lambda fn: json.loads(subprocess.check_output(
        ["node", str(DRIVER), str(path), str(data), "--args", "--fn", fn], text=True))["results"]
    library = jax.jit(step)
    expected = np.asarray([np.asarray(library(*c)) for c in calls])
    assert np.all(np.isfinite(expected))
    np.testing.assert_allclose(np.asarray(node("step")), expected, rtol=0, atol=1e-12)
    seen = jax.jit(observe)
    for c, got in zip(calls, node("observe")):
        named = dict(zip(exporter.OBSERVED, seen(*c)))
        for field, value in named.items():
            np.testing.assert_allclose(got[field], np.asarray(value), rtol=0, atol=1e-12)
        # The battery's rate, split by part, adds up to the battery's rate.
        np.testing.assert_allclose(np.sum(named["pays"][:-1]), named["pays"][-1], rtol=0, atol=1e-12)
    # The start and the curve, at random memories, carts, batteries and places.
    starts, curves = [], []
    for c in calls[::4]:
        usual, weights = rng.uniform(0, .5, len(metadata["centres"])), rng.normal(0, 1, len(metadata["centres"]))
        starts.append((c[1], rng.uniform(0, 10, count), c[2], usual, weights, rng.uniform(-8, 8, 1), rng.uniform(1, 9, 1)))
        curves.append((c[0], rng.uniform(-9, 9, 1)))
    start, curve = jax.jit(functions["start"]), jax.jit(functions["curve"])
    data.write_text(json.dumps([[np.asarray(a).tolist() for a in c] for c in starts]))
    np.testing.assert_allclose(np.asarray(node("start")), np.asarray([np.asarray(start(*c)) for c in starts]),
                               rtol=0, atol=1e-12)
    data.write_text(json.dumps([[np.asarray(a).tolist() for a in c] for c in curves]))
    for c, got in zip(curves, node("curve")):
        for field, value in zip(("usual", "density"), curve(*c)):
            np.testing.assert_allclose(got[field], np.asarray(value), rtol=0, atol=1e-12)


def test_unknown_primitive_stops_the_export():
    with pytest.raises(NotImplementedError, match="erf"):
        exporter.javascript(lambda x: jax.lax.erf(x), np.ones(3), "f")
